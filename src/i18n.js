  t(key) {
    return (this.dict[this.lang] && this.dict[this.lang][key]) || key;
  },
  apply(lang) {
    this.lang = this.dict[lang] ? lang : "ru";
    document.documentElement.setAttribute("lang", this.lang);
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = this.t(el.getAttribute("data-i18n"));
    });
    // кастомные тултипы (data-tip-i18n → атрибут data-tip)
    document.querySelectorAll("[data-tip-i18n]").forEach((el) => {
      el.setAttribute("data-tip", this.t(el.getAttribute("data-tip-i18n")));
    });
    const sel = document.getElementById("langSelect");
    if (sel) sel.value = this.lang;
  },
